#!/usr/bin/env python3
"""Select optional CUDA using installed tools only; never alter the compiler."""
import argparse
import ctypes
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tempfile


class Unavailable(Exception):
    pass


def devices():
    try:
        driver = ctypes.CDLL('libcuda.so.1')
    except OSError as error:
        raise Unavailable('NVIDIA CUDA driver is unavailable') from error
    if driver.cuInit(0) != 0:
        raise Unavailable('NVIDIA CUDA driver could not initialize')
    count = ctypes.c_int()
    if driver.cuDeviceGetCount(ctypes.byref(count)) != 0 or count.value == 0:
        raise Unavailable('no usable CUDA GPU was found')
    found = []
    for ordinal in range(count.value):
        device, major, minor = ctypes.c_int(), ctypes.c_int(), ctypes.c_int()
        if driver.cuDeviceGet(ctypes.byref(device), ordinal) != 0:
            continue
        if (driver.cuDeviceGetAttribute(ctypes.byref(major), 75, device.value) == 0
                and driver.cuDeviceGetAttribute(ctypes.byref(minor), 76, device.value) == 0):
            found.append((ordinal, f'{major.value}{minor.value}'))
    if not found:
        raise Unavailable('GPU compute capability could not be determined')
    return found


def installed_nvcc():
    candidates = [os.environ.get('CUDACXX'), shutil.which('nvcc')]
    for key in ('CUDAToolkit_ROOT', 'CUDA_PATH', 'CUDA_HOME'):
        if os.environ.get(key):
            candidates.append(str(Path(os.environ[key]) / 'bin/nvcc'))
    candidates += ['/usr/local/cuda/bin/nvcc', '/opt/cuda/bin/nvcc']
    return next((str(Path(p).resolve()) for p in candidates
                 if p and Path(p).is_file() and os.access(p, os.X_OK)), None)


def run(command, log, timeout=120):
    log.write('$ ' + shlex.join(map(str, command)) + '\n')
    log.flush()
    try:
        result = subprocess.run(command, text=True, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as error:
        log.write(str(error) + '\n')
        return None
    log.write(result.stdout)
    log.flush()
    return result.stdout if result.returncode == 0 else None


def write_options(output, enabled=False, architectures=(), nvcc=None,
                  host=None, cudnn=None):
    values = {
        'WITH_CUDA': enabled, 'WITH_CUBLAS': enabled, 'WITH_CUFFT': enabled,
        'ENABLE_CUDA_FIRST_CLASS_LANGUAGE': enabled,
        'WITH_CUDNN': bool(cudnn), 'OPENCV_DNN_CUDA': bool(cudnn),
    }
    lines = ['# Generated by detect-cuda.py; applies only to this OpenCV build.']
    for key, value in values.items():
        lines.append(f'set({key} {"ON" if value else "OFF"} CACHE BOOL "" FORCE)')
    if enabled:
        strings = {
            'CMAKE_CUDA_COMPILER': nvcc,
            'CMAKE_CUDA_HOST_COMPILER': host,
            'CMAKE_CUDA_ARCHITECTURES': ';'.join(a + '-real' for a in architectures),
            'CUDA_ARCH_BIN': ';'.join(a[:-1] + '.' + a[-1] for a in architectures),
            'CUDA_ARCH_PTX': '',
        }
        if cudnn:
            strings.update(cudnn)
        for key, value in strings.items():
            # Bracket quoting prevents CMake from expanding paths as code.
            if ']==]' in value:
                raise ValueError('Unsupported delimiter in CUDA path')
            lines.append(f'set({key} [==[{value}]==] CACHE STRING "" FORCE)')
    output.write_text('\n'.join(lines) + '\n')


def detect(output, probe_dir, log):
    nvcc = installed_nvcc()
    if not nvcc:
        raise Unavailable('CUDA toolkit (nvcc) is not installed')
    compiler = shlex.split(os.environ.get('CXX', 'c++'))
    if len(compiler) != 1 or not shutil.which(compiler[0]):
        raise Unavailable('the current C++ compiler cannot be checked safely')
    host = shutil.which(compiler[0])
    gpu_devices = devices()
    codes = run([nvcc, '--list-gpu-code'], log, timeout=20)
    if codes is None:
        raise Unavailable('nvcc could not report its supported GPU architectures')
    supported = set(re.findall(r'\bsm_([0-9]+)\b', codes))
    selected = [(device, arch) for device, arch in gpu_devices if arch in supported]
    if not selected:
        raise Unavailable('installed CUDA toolkit does not support the detected GPU architecture')
    architectures = sorted({arch for _, arch in selected}, key=int)
    if len(selected) != len(gpu_devices):
        print('OpenCV CUDA: ignoring GPUs unsupported by the installed toolkit')

    assets = Path(__file__).resolve().parent
    source = probe_dir / 'source'
    source.mkdir()
    shutil.copyfile(assets / 'cuda-probe.cmake', source / 'CMakeLists.txt')
    shutil.copyfile(assets / 'cuda-probe.cu', source / 'probe.cu')
    command = ['cmake', '-S', str(source), '-B', str(probe_dir),
               f'-DCMAKE_CUDA_COMPILER={nvcc}', f'-DCMAKE_CUDA_HOST_COMPILER={host}',
               f'-DCMAKE_CXX_COMPILER={host}', '-DCMAKE_CUDA_STANDARD=17',
               '-DCMAKE_BUILD_TYPE=Release',
               '-DCMAKE_CUDA_ARCHITECTURES=' + ';'.join(a + '-real' for a in architectures)]
    if run(command, log) is None:
        raise Unavailable('CUDA cannot configure with the current compiler/toolkit libraries')
    if run(['cmake', '--build', str(probe_dir), '--target', 'cuda_probe', '-j1'], log) is None:
        raise Unavailable('CUDA test cannot compile with the current compiler/toolkit')
    usable = [(device, arch) for device, arch in selected
              if run([str(probe_dir / 'cuda_probe'), str(device)], log, 30) is not None]
    if not usable:
        raise Unavailable('CUDA/cuBLAS/cuFFT/NPP test failed on the detected GPU')
    architectures = sorted({arch for _, arch in usable}, key=int)

    cache = (probe_dir / 'CMakeCache.txt').read_text()
    cudnn = {}
    for key in ('CUDNN_INCLUDE_DIR', 'CUDNN_LIBRARY'):
        match = re.search(r'^' + key + r':(?:PATH|FILEPATH)=(.+)$', cache, re.M)
        if match and not match[1].endswith('-NOTFOUND'):
            cudnn[key] = match[1]
    if len(cudnn) != 2:
        cudnn = None
        print('OpenCV CUDA: cuDNN is not installed; CUDA AI backend disabled')
    elif (run(['cmake', '--build', str(probe_dir), '--target', 'cudnn_probe', '-j1'], log) is None
          or any(run([str(probe_dir / 'cudnn_probe'), str(device)], log, 30) is None
                 for device, _ in usable)):
        cudnn = None
        print('OpenCV CUDA: cuDNN test failed; CUDA AI backend disabled')
    write_options(output, True, architectures, nvcc, host, cudnn)
    print('OpenCV CUDA: enabled for ' + ', '.join('sm_' + a for a in architectures)
          + f'; current host compiler: {host}; CUDA AI: {"enabled" if cudnn else "disabled"}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--probe-dir', type=Path, required=True)
    parser.add_argument('--cpu-only', action='store_true')
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    write_options(args.output)
    if args.cpu_only:
        print('OpenCV CUDA: disabled; building CPU support')
        return
    args.probe_dir.mkdir(parents=True, exist_ok=True)
    logfile = args.probe_dir / 'compatibility.log'
    # Never reuse an earlier compiler/toolkit check's CMake cache.
    with logfile.open('w') as log, tempfile.TemporaryDirectory(
            prefix='check-', dir=args.probe_dir) as scratch:
        try:
            detect(args.output, Path(scratch), log)
        except (Unavailable, OSError, ValueError, AttributeError) as error:
            log.write(str(error) + '\n')
            print(f'OpenCV CUDA: disabled ({error}); building CPU support')
        print(f'OpenCV CUDA compatibility log: {logfile}')


if __name__ == '__main__':
    main()
